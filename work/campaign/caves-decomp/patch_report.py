def sub(pattern, new_text, label):
    global R
    rx = re.compile(pattern)
    hits = [i for i, l in enumerate(R) if rx.search(l)]
    if len(hits) != 1:
        raise SystemExit("!! %s: %d совпадений по /%s/" % (label, len(hits), pattern[:60]))
    i = hits[0]
    R[i] = rx.sub(lambda m: new_text, R[i], count=1)
    print("   строка %d: %s" % (i + 1, label))


