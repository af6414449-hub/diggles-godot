def patch(path, pairs, append=None, insert_before=None):
    with io.open(path, "r", encoding="utf-8") as f:
        text = f.read()
    for old, new, count in pairs:
        n = text.count(old)
        if n != count:
            print(f"!! {os.path.basename(path)}: вхождений {n}, ожидалось {count}: {old[:70]!r}")
            sys.exit(1)
        text = text.replace(old, new)
    if insert_before:
        anchor, block = insert_before
        if text.count(anchor) != 1:
            print(f"!! anchor {anchor!r} не найден в {os.path.basename(path)}")
            sys.exit(1)
        text = text.replace(anchor, block + anchor)
    if append:
        text = text.rstrip("\n") + "\n" + append
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"ok: {os.path.basename(path)} ({len(text)} символов)")


