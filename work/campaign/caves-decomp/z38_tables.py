RE_DWORD = re.compile(r'^\s*([A-Za-z_]\w*)\[(\d+)\]\s*=\s*0x([0-9A-Fa-f]{1,8});')
RE_WORD  = re.compile(r'^\s*\*\(undefined2 \*\)\(\(?(?:int\))?(\w+) \+ (\d+)\)\s*=\s*(0x[0-9A-Fa-f]{1,4}|\d+);')
RE_BYTE  = re.compile(r'^\s*\*\(undefined1 \*\)\(\(?(?:int\))?(\w+) \+ (\d+)\)\s*=\s*(0x[0-9A-Fa-f]{1,2}|\d+);')
RE_LEN   = re.compile(r'^\s*([A-Za-z_]\w*)\[2\]\s*=\s*(0x[0-9A-Fa-f]+|\d+);')
RE_FIELD = re.compile(r'^\s*(?:local_24|local_2c|\*local_24|\*local_2c)\[?(0x[0-9A-Fa-f]+|\d+)?\]?\s*=\s*(0x[0-9A-Fa-f]+|-?\d+);')
RE_AD    = re.compile(r'FUN_00455ad0\(([^)]*)\);')

TS_NAMES = ['ColorOp','ColorArg1','ColorArg1Tfac','ColorArg2','ColorArg2Tfac','AlphaOp',
            'AlphaArg1','AlphaArg1Tfac','AlphaArg2','AlphaArg2Tfac','MagFilter','MinFilter',
            'MipFilter','MaxAniso','MaxMipLevel','Address','AddressU','AddressV']
TQ_NAMES = ['ZEnable','ZWriteEnable','ZFuncMode','AlphaEnable','AlphaTestEnable','AlphaFuncMode',
            'AlphaRefValue','SrcBlend','DestBlend','SpecularEnable','CullMode','Lighting',
            'GlowEnable','GlowSize','GlowColor','EnvMapEnable','Internal40',
            'TextStage0','TextStage1','TextStage2','TextStage3','TextStage4','TextStage5',
            'TextStage6','TextStage7']


def parse(path, reg_fn, nfields, stride):
    cur, pend = {}, []
    recs = []
    rec = None
    pending_parent = None
    mode = 'idle'          # 'name' -> building the name string object; 'record' -> filling the record
    for ln in open(path, 'r', encoding='utf-8', errors='replace'):
        s = ln.strip()
        if 'FUN_006ba810(0x19' in s:
            mode = 'name'
        m = RE_DWORD.match(s)
        if m:
            var, idx, val = m.group(1), int(m.group(2)), int(m.group(3), 16)
            if idx >= 3:
                off = (idx - 3) * 4
                b = val.to_bytes(4, 'little')
                for k in range(4):
                    cur.setdefault(var, {})[off + k] = bytes([b[k]])
                continue
        m = RE_WORD.match(s)
        if m:
            var, idx, val = m.group(1), int(m.group(2)), int(m.group(3), 0)
            off = (idx - 3) * 4
            b = (val & 0xFFFF).to_bytes(2, 'little')
            for k in range(2):
                cur.setdefault(var, {})[off + k] = bytes([b[k]])
            continue
        m = RE_BYTE.match(s)
        if m:
            var, idx, val = m.group(1), int(m.group(2)), int(m.group(3), 0)
            cur.setdefault(var, {})[(idx - 3) * 4] = bytes([val & 0xFF])
            continue
        m = RE_LEN.match(s)
        if m:
            var, L = m.group(1), int(m.group(2), 0)
            d = cur.get(var, {})
            if d:
                buf = bytearray()
                for off in range(L):
                    buf += d.get(off, b'\x00')[:1]
                z = buf.find(b'\x00')
                if z >= 0:
                    buf = buf[:z]
                pend.append(buf.decode('latin1'))
                cur[var] = {}
            continue
        if reg_fn in s:
            name = pend.pop() if pend else '???'
            rec = {'id': len(recs), 'name': name, 'f': {}, 'parent': pending_parent}
            pending_parent = None
            recs.append(rec)
            mode = 'record'
            continue
        if rec is not None and mode == 'record':
            m2 = RE_FIELD.match(s)
            if m2:
                idx = m2.group(1)
                v = int(m2.group(2), 0)
                if idx is None:
                    rec['f'][0] = v
                else:
                    k = int(idx, 0)
                    if k < nfields:
                        rec['f'][k] = v
                continue
        m3 = RE_AD.search(s)
        if m3:
            a = m3.group(1)
            off = 0
            mm = re.search(r'\+\s*(0x[0-9A-Fa-f]+|\d+)', a)
            if mm:
                off = int(mm.group(1), 0)
            pending_parent = off // stride
    return recs


