# -*- coding: utf-8 -*-
"""Помечает D25 закрытым (З37) в инвентаре З32 — и в z32.md, и в report.md."""
import io
from pathlib import Path

ZONE = Path(r"C:\Users\frant\OneDrive\Документы\MiniMax\Diggles\work\campaign\caves-decomp")
REPORT = ZONE / "report.md"
Z32 = ZONE / "z32.md"

MARK = "<!-- D25-CLOSED-BY-Z37 -->"

OLD_ROW = "| D25 | Отсечение объектов (frustum/видимость) | — | **ОТКРЫТО** (не найдено) | З32 п.4 |"
NEW_ROW = ("| D25 | Отсечение объектов (frustum/видимость) | `FUN_00445e40`, `CScapeRenderer__RenderScape` "
           "| **ЗАКРЫТО** | З37 |")

OLD_ROW2 = "| D25 | Отсечение объектов — ОТКРЫТО | **Переформулирован**: отдельного отсечения по тайлам нет; осталось выяснить, есть ли отсечение по видимости/расстоянию вообще |"
NEW_ROW2 = ("| D25 | Отсечение объектов — ЗАКРЫТО | **Закрыто в З37**: отсечения пирамидой видимости нет; "
            "видимая область = проекция камеры на z=0 → полигон → список отрезков клеток; объекты не отсекаются |")

OLD_TXT = """* **D25 — отсечение.** Поиск по строкам `cull|frustum|ClipPlane` в exe дал
  только два попадания (в парсере шейдеров) ⇒ отдельного отсечения камерой,
  вероятно, нет: роль отсечения играет разбиение по 1024 тайлам на тип."""

NEW_TXT = """* **D25 — отсечение. ЗАКРЫТО в З37.** Поиск по строкам `cull|frustum|ClipPlane` в exe дал
  только два попадания (в парсере шейдеров) ⇒ отдельного отсечения камерой нет.
  Разбиение по 1024 тайлам на тип — ложный следствие (З33).
  **Как на самом деле:** видимая область = проекция камеры на плоскость z = 0 →
  полигон → список отрезков клеток `(x0, y0, countX)`; по нему рисуются земля,
  стены/поверхности, жидкости и выбираются высоты; отступ 2 клетки от края карты;
  обычные объекты не отсекаются вовсе (З37)."""

NOTE = ("<!-- D25-CLOSED-BY-Z37 -->\n"
        "> **ЗАКРЫТО в З37.** Отсечения по пирамиде видимости в оригинале нет.\n"
        "> Видимая область вычисляется как **проекция камеры на плоскость z = 0 → полигон →\n"
        "> список отрезков клеток `(x0, y0, countX)`** (`FUN_00445e40`), и по нему идёт\n"
        "> построчный обход земли/стен/жидкостей. Обычные объекты **не отсекаются вообще**.\n"
        "> Подробности — З37.\n\n")

for path in (Z32, REPORT):
    txt = io.open(path, encoding="utf-8").read()
    if MARK in txt:
        print(f"{path.name}: уже помечено, пропуск")
        continue
    changed = 0
    for old, new in ((OLD_ROW, NEW_ROW), (OLD_ROW2, NEW_ROW2), (OLD_TXT, NEW_TXT)):
        n = txt.count(old)
        if n == 1:
            txt = txt.replace(old, new, 1)
            changed += 1
        elif n > 1:
            raise SystemExit(f"{path.name}: неоднозначно ({n}) для {old[:40]!r}")
    # плашка после таблицы Д-инвентаря: вставляем перед "## 5." или "## 6."
    if changed == 0:
        raise SystemExit(f"{path.name}: ничего не заменено")
    # ставим плашку сразу после строки-заголовка таблицы D
    anchor = "| D29 | Семантика `[2]…[0xb]` в `FUN_0043fd30` | `FUN_0043fd30` | **ОТКРЫТО** | З30 |"
    if txt.count(anchor) == 1:
        txt = txt.replace(anchor, anchor + "\n" + NOTE.rstrip(), 1)
    else:
        print(f"{path.name}: anchor D29 не найден, плашка не вставлена (замен: {changed})")
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(txt)
    print(f"{path.name}: D25 помечен закрытым (замен: {changed})")
