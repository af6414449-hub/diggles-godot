def apply(name, pairs):
    p = os.path.join(BASE, name)
    s = io.open(p, encoding="utf-8").read()
    for old, new in pairs:
        n = s.count(old)
        if n != 1:
            raise SystemExit("!! %s: вхождений %d для %r" % (name, n, old[:70]))
        s = s.replace(old, new)
    io.open(p, "w", encoding="utf-8", newline="").write(s)
    print("ok:", name, "(%d правок)" % len(pairs))


for name, pairs in FIX.items():
    apply(name, pairs)
