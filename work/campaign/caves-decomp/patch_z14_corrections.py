def load(name):
    p = os.path.join(base, name)
    raw = open(p, "rb").read()
    bom = raw.startswith(b"\xef\xbb\xbf")
    return p, bom, raw.decode("utf-8-sig")

def save(p, bom, text):
    out = text.encode("utf-8")
    if bom:
        out = b"\xef\xbb\xbf" + out
    open(p, "wb").write(out)

