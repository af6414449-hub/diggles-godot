def load(name):
    p = os.path.join(BASE, name)
    return p, io.open(p, encoding="utf-8").read().splitlines()


def save(name, lines):
    p = os.path.join(BASE, name)
    io.open(p, "w", encoding="utf-8", newline="\r\n").write("\n".join(lines))
    print("ok:", name)


def replace_line(lines, startswith, new_lines, label):
    hits = [i for i, l in enumerate(lines) if l.startswith(startswith)]
    if len(hits) != 1:
        raise SystemExit("!! %s: %d строк начинаются с %r" % (label, len(hits), startswith[:60]))
    i = hits[0]
    lines[i:i + 1] = new_lines
    print("   заменена строка %d: %s" % (i + 1, label))


def replace_sub(lines, pattern, new_text, label, flags=0):
    rx = re.compile(pattern, flags)
    hits = [i for i, l in enumerate(lines) if rx.search(l)]
    if len(hits) != 1:
        raise SystemExit("!! %s: %d совпадений по /%s/" % (label, len(hits), pattern[:60]))
    i = hits[0]
    lines[i] = rx.sub(lambda m: new_text, lines[i], count=1)
    print("   заменена строка %d: %s" % (i + 1, label))


